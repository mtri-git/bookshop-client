export default function Icon({ name, className = 'w-5 h-5', strokeWidth = 2, title, ...rest }) {
	const icon = ICONS[name]
	if (!icon) {
		if (import.meta.env.DEV) console.warn(`Icon "${name}" not found`)
		return null
	}
	const paint = icon.custom
		? { fill: 'none' }
		: icon.solid
			? { fill: 'currentColor' }
			: { fill: 'none', stroke: 'currentColor', strokeWidth, strokeLinecap: 'round', strokeLinejoin: 'round' }
	return (
		<svg
			xmlns='http://www.w3.org/2000/svg'
			viewBox={icon.viewBox}
			className={`shrink-0 ${className}`}
			aria-hidden={title ? undefined : true}
			role={title ? 'img' : undefined}
			focusable='false'
			{...paint}
			{...rest}>
			{title && <title>{title}</title>}
			{icon.body}
		</svg>
	)
}
